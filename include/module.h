#ifndef MM41_MODULE_H
#define MM41_MODULE_H

#include "ops.h"

/* A module is a named set of commands with optional setup and teardown.
 *
 * Built-in modules live in modules/<name>/ and are compiled in according to
 * the MODULES list in the Makefile; each one defines
 *
 *     const Module mm41_mod_<name> = { "name", "1.0", "summary", ops, n, init, shutdown };
 *
 * At startup the registry concatenates the tables of all modules into one
 * flat dispatch table (ops[], n_ops) in registration order, so an execution
 * token (@name) is simply an index into that table. Everything that reads
 * the table -- dispatch, usage, listfcns, completion, the generated
 * reference -- works on the flat table and never needs to know about
 * modules; module_of() recovers the module for display.
 *
 * The same struct is what a shared-object module will export through
 *     const Module *mm41_module(void);
 * so a module compiled in or loaded at run time is the same thing. */

#define MM41_MODULE_API 1

typedef struct Module {
  const char *name;       /* "matrices" */
  const char *version;    /* "1.0" */
  const char *summary;    /* one line for `modules` */
  const Op   *ops;
  int         n_ops;
  int  (*init)(void);     /* optional; nonzero return aborts startup */
  void (*shutdown)(void); /* optional */
} Module;

/* The registry. */
int           modules_register(const Module *m);   /* 0 on success */
int           modules_init_all(void);              /* call every init, build the flat table */
void          modules_shutdown_all(void);
int           modules_count(void);
const Module *module_at(int i);
const Module *module_find(const char *name);
const Module *module_of(int op_index);             /* module owning ops[op_index] */
int           module_first_op(const Module *m);    /* index of its first command in ops[] */
void          list_modules(void);                  /* the `modules` command */

/* The list of built-in modules, generated by the Makefile from MODULES. */
extern const Module *const mm41_builtin_modules[];

#endif
